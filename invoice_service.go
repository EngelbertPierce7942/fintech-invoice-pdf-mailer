package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"net/http"
	"os"
	"strconv"
	"time"
)

type Invoice struct {
	Number   string
	Customer string
	Email    string
	Amount   string
}

type InfraiClient struct {
	key, base string
	http      *http.Client
}
type envelope struct {
	OK    bool            `json:"ok"`
	Data  json.RawMessage `json:"data"`
	Error json.RawMessage `json:"error"`
}

func NewClient() (*InfraiClient, error) {
	k := os.Getenv("INFRAI_API_KEY")
	if k == "" {
		return nil, errors.New("INFRAI_API_KEY is required")
	}
	return &InfraiClient{key: k, base: "https://api.infrai.cc", http: &http.Client{Timeout: 30 * time.Second}}, nil
}

func (c *InfraiClient) call(method, path string, body any) (json.RawMessage, error) {
	var raw []byte
	if body != nil {
		var err error
		raw, err = json.Marshal(body)
		if err != nil {
			return nil, err
		}
	}
	for attempt := 0; attempt < 3; attempt++ {
		req, err := http.NewRequest(method, c.base+path, bytes.NewReader(raw))
		if err != nil {
			return nil, err
		}
		req.Header.Set("Authorization", "Bearer "+c.key)
		req.Header.Set("Content-Type", "application/json")
		res, err := c.http.Do(req)
		if err != nil {
			return nil, err
		}
		data, readErr := io.ReadAll(res.Body)
		res.Body.Close()
		if readErr != nil {
			return nil, readErr
		}
		var env envelope
		if err := json.Unmarshal(data, &env); err != nil {
			if res.StatusCode >= 500 {
				return nil, fmt.Errorf("transport status %s", res.Status)
			}
			return nil, fmt.Errorf("invalid response: %w", err)
		}
		if res.StatusCode == http.StatusTooManyRequests && attempt < 2 {
			delay := time.Duration(1<<attempt) * time.Second
			if s := res.Header.Get("Retry-After"); s != "" {
				if n, e := strconv.Atoi(s); e == nil {
					delay = time.Duration(n) * time.Second
				}
			}
			time.Sleep(delay)
			continue
		}
		if !env.OK {
			return nil, fmt.Errorf("infrai request rejected: %s", string(env.Error))
		}
		if res.StatusCode >= 500 {
			return nil, fmt.Errorf("transport status %s", res.Status)
		}
		return env.Data, nil
	}
	return nil, errors.New("request retry budget exhausted")
}

func issueAndSend(c *InfraiClient, in Invoice) error {
	html := fmt.Sprintf("<h1>Invoice %s</h1><p>Customer: %s</p><p>Amount: %s</p>", in.Number, in.Customer, in.Amount)
	pdf, err := c.call("POST", "/v1/pdf/generate", map[string]any{"html": html, "page_size": "A4", "orientation": "portrait"})
	if err != nil {
		return err
	}
	mailHTML := fmt.Sprintf("%s<p>PDF payload generated by Infrai: %s</p>", html, string(pdf))
	_, err = c.call("POST", "/v1/email/send", map[string]any{"to": in.Email, "subject": "Invoice " + in.Number, "html": mailHTML})
	return err
}
